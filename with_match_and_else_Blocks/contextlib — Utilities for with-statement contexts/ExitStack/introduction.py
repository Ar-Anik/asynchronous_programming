import contextlib

def write_to_multiple_files(file_list):
    # ExitStack-এর একটি object তৈরি করা হলো
    with contextlib.ExitStack() as stack:
        file_objects = []

        # ডাইনামিক উপায়ে লুপের মাধ্যমে ফাইল ওপেন করা হচ্ছে
        for filename in file_list:
            # enter_context মেথডটি ফাইলের context manager-কে স্ট্যাকে রেজিস্টার করে
            f = stack.enter_context(open(filename, 'w'))
            file_objects.append(f)

        # এখন সমস্ত ফাইল একসাথে ওপেন আছে এবং সেগুলোতে write করা সম্ভব
        for index, file_obj in enumerate(file_objects):
            file_obj.write(f"ফাইল নম্বর {index + 1}-এর জন্য সংরক্ষিত টেক্সট।")

        print(f"সফলভাবে {len(file_list)}টি ফাইলে write সম্পন্ন হয়েছে।")

    # with ব্লক থেকে বের হওয়ার সাথে সাথে ExitStack স্বয়ংক্রিয়ভাবে (automatic)
    # সমস্ত ফাইলকে LIFO ক্রমানুসারে বন্ধ (close) করে দেবে।

# ফাইলের একটি ডাইনামিক তালিকা (এখানে ৩টি, তবে এটি যেকোনো সংখ্যার হতে পারে)
names_of_files = ['report_a.txt', 'report_b.txt', 'report_c.txt']
write_to_multiple_files(names_of_files)
