iterator = cur.__aiter__()
while True:
    try:
        # ১. __anext__() একটি coroutine object রিটার্ন করে, সরাসরি ডাটা নয়
        coro = iterator.__anext__()

        # ২. সেই coroutine object-টিকে await করা হয় যেন event loop ব্লক না হয়
        row = await coro

        # লুপের ভেতরের কোড এখানে কাজ করে
    except StopAsyncIteration:
        break

"""
একটি সাধারণ পাইথন অ্যারে বা লিস্ট থেকে সরাসরি __anext__() মেথড ব্যবহার করে ডাটা ফেচ (fetch) করা সম্ভব নয়। পাইথনের বিল্ট-ইন লিস্ট বা অ্যারে হলো সিনক্রোনাস ইটারেবল (synchronous iterable)। এর ভেতরের উপাদানগুলো মেমরিতে একসাথে জমা থাকে এবং এগুলোকে রিড করার জন্য পাইথন __next__() মেথড ব্যবহার করে। এই বিল্ট-ইন ইটারেটরের মধ্যে __anext__() নামক কোনো মেথড define করা থাকে না।
যদি কোনো সাধারণ লিস্টের ওপর async for লুপ চালানো হয়:
"""
async def fetch_data():
    my_list = [1, 2, 3]
    async for item in my_list:
        print(item)

asyncio.run(fetch_data())

