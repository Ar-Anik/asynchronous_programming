"""
অ্যাসিনক্রোনাস ইটারেশন এবং অ্যাসিনক্রোনাস ইটারেবল (Asynchronous Iteration and Asynchronous Iterables)
"Asynchronous Context Managers" অংশে দেখা গেছে কীভাবে async with এমন সব object-এর সাথে কাজ করে যা __aenter__ এবং __aexit__ মেথড ইমপ্লিমেন্ট করে এবং অ্যাওয়েটেবল (awaitable)—সাধারণত coroutine object হিসেবে—রিটার্ন করে।

ঠিক একইভাবে, async for অ্যাসিনক্রোনাস ইটারেবলের (asynchronous iterables) সাথে কাজ করে। এগুলো হলো এমন object যা __aiter__ মেথড ইমপ্লিমেন্ট করে। তবে, এই __aiter__ অবশ্যই একটি সাধারণ মেথড (regular method) হতে হবে—কোনো কোরুটিন মেথড (coroutine method) হওয়া যাবে না এবং এটি অবশ্যই একটি অ্যাসিনক্রোনাস ইটারেটর (asynchronous iterator) রিটার্ন করবে।

অ্যাসিনক্রোনাস ইটারেটরের কার্যপদ্ধতি
একটি অ্যাসিনক্রোনাস ইটারেটর একটি __anext__ কোরুটিন মেথড প্রদান করে যা একটি awaitable রিটার্ন করে—যা প্রায়শই একটি coroutine object। এগুলোর কাছ থেকে __aiter__ ইমপ্লিমেন্ট করারও প্রত্যাশা করা হয়, যা সাধারণত self রিটার্ন করে। এটি ইটারেবল (iterable) এবং ইটারেটরের (iterator) মধ্যকার সেই গুরুত্বপূর্ণ পার্থক্যকে প্রতিফলিত করে, যা "Don’t Make the Iterable an Iterator for Itself" অংশে আলোচনা করা হয়েছে।

একটি বাস্তবসম্মত উদাহরণ: aiopg
aiopg অ্যাসিনক্রোনাস PostgreSQL ড্রাইভারের ডকুমেন্টেশনে একটি উদাহরণ রয়েছে, যা ডেটাবেজ কার্সারের (database cursor) রোগুলোর (rows) ওপর ইটারেট (iterate) করার জন্য async for এর ব্যবহার প্রদর্শন করে:
"""

async def go():
    pool = await aiopg.create_pool(dsn)
    async with pool.acquire() as conn:
        async with conn.cursor() as cur:
            await cur.execute("SELECT 1")
            ret = []
            async for row in cur:
                ret.append(row)
            assert ret == [(1,)]

"""
aiopg হলো একটি PostgreSQL ডেটাবেজ ড্রাইভার। এটি কাজ করার জন্য একটি active PostgreSQL ডেটাবেজ সার্ভার থাকা আবশ্যক, যার কানেকশন ডিটেইলস dsn(Data Source Name) string হিসেবে পাস করতে হয়।
"""

"""
এই উদাহরণে কুয়েরিটি (query) একটি মাত্র রো (row) রিটার্ন করবে, কিন্তু বাস্তবসম্মত ক্ষেত্রে একটি SELECT কুয়েরির রেসপন্স হিসেবে হাজার হাজার রো থাকতে পারে। বড় রেসপন্সের ক্ষেত্রে, কার্সারটি একটি একক ব্যাচে (single batch) সব রো একসাথে লোড করে না।

তাই এটি অত্যন্ত গুরুত্বপূর্ণ যে, কার্সারটি যখন অতিরিক্ত রো-এর জন্য অপেক্ষা করতে পারে, তখন যেন async for row in cur: অংশটি ইভেন্ট লুপকে (event loop) ব্লক (block) না করে। কার্সারটিকে একটি অ্যাসিনক্রোনাস ইটারেটর হিসেবে ইমপ্লিমেন্ট করার মাধ্যমে, aiopg প্রতিটি __anext__ কলের সময় ইভেন্ট লুপের কাছে নিয়ন্ত্রণ ছেড়ে দিতে (yield) পারে এবং পরবর্তীতে যখন PostgreSQL থেকে আরও রো আসবে তখন পুনরায় কাজ শুরু (resume) করতে পারে।
"""

# Full Code :
import asyncio
import aiopg

# একটি সঠিক DSN (Data Source Name) স্ট্রিং define করতে হবে
# ফরম্যাট: 'dbname=ডেটাবেজ_নাম user=ইউজার_নাম password=পাসওয়ার্ড host=হোস্ট_অ্যাড্রেস'
dsn = 'dbname=test_db user=postgres password=secret host=127.0.0.1'


async def go():
    try:
        # একটি কানেকশন পুল তৈরি করা হচ্ছে
        pool = await aiopg.create_pool(dsn)

        # পুল থেকে একটি কানেকশন নেওয়া হচ্ছে
        async with pool.acquire() as conn:
            # একটি কার্সার তৈরি করা হচ্ছে
            async with conn.cursor() as cur:
                # SQL কোয়েরি execute করা হচ্ছে
                await cur.execute("SELECT 1")
                ret = []

                # অ্যাসিনক্রোনাস লুপের মাধ্যমে ডাটা রিড করা হচ্ছে
                async for row in cur:
                    ret.append(row)

                # আউটপুট যাচাই করা হচ্ছে
                assert ret == [(1,)]
                print("কোডটি সফলভাবে execute হয়েছে। আউটপুট:", ret)

    except Exception as e:
        print("ত্রুটি ঘটেছে:", e)


if __name__ == '__main__':
    # asyncio event loop চালু করে go object-টি রান করা হচ্ছে
    asyncio.run(go())

"""
কোডটি run করার জন্য প্রয়োজনীয় পদক্ষেপ
১. প্যাকেজ ইনস্টল করা: টার্মিনালে বা কমান্ড প্রম্পটে নিচের command ব্যবহার করে aiopg ইনস্টল করতে হবে:
        pip install aiopg
২. PostgreSQL সার্ভার: নিশ্চিত করতে হবে যে একটি PostgreSQL সার্ভার active আছে এবং সেখানে একটি ডেটাবেজ তৈরি করা আছে।
৩. ক্রেডেনশিয়াল পরিবর্তন: কোডের dsn স্ট্রিং-এর ভেতর নিজের ডেটাবেজের সঠিক dbname, user, password এবং host বসাতে হবে। এরপর ফাইলটি সংরক্ষণ করে পাইথন দিয়ে run করলে এটি সঠিকভাবে কাজ করবে।
"""

"""
১. সিনক্রোনাস ইটারেটর (__next__): সরাসরি ডাটা প্রদান
একটি সাধারণ অ্যারে বা লিস্ট [1, 2, 3] এর ক্ষেত্রে সমস্ত ডাটা আগে থেকেই মেমরিতে বা স্টোরেজে (storage) জমা থাকে। যখন প্রথমবার __next__() কল করা হয়, তখন এটি মেমরি থেকে সরাসরি প্রথম উপাদান 1 রিটার্ন করে। এই প্রক্রিয়ায় কোনো অপেক্ষার বিষয় থাকে না। এটি একটি সাধারণ ফাংশন কল হিসেবে কাজ করে এবং ডাটা না পাওয়া পর্যন্ত কোডের পরবর্তী লাইন এক্সিকিউট (execute) হয় না।

২. অ্যাসিনক্রোনাস ইটারেটর (__anext__): ভবিষ্যতের জন্য প্রতিশ্রুতি
অ্যাসিনক্রোনাস ক্ষেত্রে (যেমন: ডেটাবেজ কার্সার থেকে হাজার হাজার রো নিয়ে আসা বা নেটওয়ার্ক থেকে ডাটা ডাউনলোড করা) ডাটা আসার প্রক্রিয়াটি তাৎক্ষণিক নাও হতে পারে। নেটওয়ার্কের বিলম্ব বা ডেটাবেজের ইন্টারনাল (internal) প্রসেসিং এর কারণে পরবর্তী ডাটা আসতে কিছুটা সময় লাগতে পারে।

এই পরিস্থিতিতে যদি সিনক্রোনাস মেথডের মতো সরাসরি ডাটা রিটার্ন করার চেষ্টা করা হতো, তবে ডাটা না আসা পর্যন্ত পুরো সিস্টেম (system) ব্লক বা অচল হয়ে বসে থাকত। এই সমস্যা সমাধানের জন্য __anext__() সরাসরি ডাটা রিটার্ন না করে একটি coroutine object রিটার্ন করে।


যখন async for row in cur: কমান্ডটি (command) চালানো হয়, তখন পাইথন ব্যাকএন্ডে একটি সুনির্দিষ্ট সিকোয়েন্স (sequence) অনুসরণ করে ডাটা উদ্ধার করে:

Step-১: পাইথন প্রথমে ইটারেটরের __anext__() মেথডটি কল করে। যেহেতু এটি একটি কোরুটিন মেথড, এটি তাৎক্ষণিকভাবে কোনো ডাটা দেয় না, বরং একটি coroutine object রিটার্ন করে।

Step-২: পাইথন অটোমেটিকভাবে (automatic) এই প্রাপ্ত coroutine object-এর সামনে একটি await কিওয়ার্ড বসিয়ে দেয় (অর্থাৎ: await iterator.__anext__())।

Step-৩: যখন এই coroutine object-টি await হয়, তখন চলমান টাস্কটি সাময়িকভাবে স্থগিত হয়ে যায় এবং ইভেন্ট লুপের (event loop) কাছে নিয়ন্ত্রণ চলে যায়। ডেটাবেজ থেকে ডাটা আসতে যতক্ষণ সময় লাগবে, ইভেন্ট লুপ ততক্ষণ বসে না থেকে অন্য কোনো টাস্ক execute করতে পারে।

Step-৪: ব্যাকগ্রাউন্ডে যখন ডেটাবেজ থেকে কাঙ্ক্ষিত ডাটাটি এসে পৌঁছায়, তখন ইভেন্ট লুপ এই স্থগিত থাকা টাস্কটিকে পুনরায় সক্রিয় (resume) করে। তখন await প্রক্রিয়াটি সম্পন্ন হয় এবং coroutine object-এর ভেতর থেকে আসল ডাটাটি (যেমন: প্রথম রো) বের হয়ে row ভ্যারিয়েবলের মধ্যে জমা হয়।
"""

# Synchronous Loop
iterator = iter([1, 2, 3])
while True:
    try:
        # __next__() সরাসরি ডাটা (যেমন: 1, 2) রিটার্ন করে
        row = iterator.__next__()
        # লুপের ভেতরের কোড এখানে কাজ করে
    except StopIteration:
        break

# Asynchronous Loop
